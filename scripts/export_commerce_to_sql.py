"""G5A SQL exporter dry-run (A113 JSON->SQL part; no database required).

Generates DDL per ADR-0002 (tables, common columns, domain unique keys)
plus INSERT statements for every commerce ledger row, and a reconciliation
footer (row counts per table, CNY money nets for the ledger). Output is a
.sql file meant for review/load later -- running it against a real
PostgreSQL instance is the separate, approval-gated migration step.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from decimal import Decimal, InvalidOperation
from pathlib import Path

COMMERCE_TABLES = {
    "offers.json": "offers",
    "matches.json": "matches",
    "opportunities.json": "opportunities",
    "decisions.json": "decisions",
    "agent_jobs.json": "agent_jobs",
    "import_batches.json": "import_batches",
    "intake_confirmations.json": "intake_confirmations",
    "radar_events.json": "radar_events",
    "radar_reminders.json": "radar_reminders",
    "opportunity_adoptions.json": "opportunity_adoptions",
    "procurement_orders.json": "procurement_orders",
    "budget_reservations.json": "budget_reservations",
    "inventory.json": "inventory",
    "ledger.json": "ledger",
}
COMMON_DDL = """
CREATE TABLE IF NOT EXISTS {table} (
    record_id     TEXT PRIMARY KEY,
    record_type   TEXT,
    scope         TEXT,
    account_id    TEXT,
    source_ref    TEXT,
    trace_id      TEXT,
    created_at    TIMESTAMPTZ,
    revision      INTEGER,
    payload       JSONB NOT NULL
);
"""
# Codex S: ledger reversals must point at a real original entry at load
# time -- reversal_of is a first-class column with a self-referential FK
LEDGER_DDL = """
CREATE TABLE IF NOT EXISTS ledger (
    record_id     TEXT PRIMARY KEY,
    record_type   TEXT,
    scope         TEXT,
    account_id    TEXT,
    source_ref    TEXT,
    trace_id      TEXT,
    created_at    TIMESTAMPTZ,
    revision      INTEGER,
    payload       JSONB NOT NULL,
    reversal_of   TEXT REFERENCES ledger(record_id)
);
"""
# Codex S: the execution authority is a top-level ledger with its own
# key (job_id); migrate it as its own table so UNKNOWN facts survive
EXECUTION_DDL = """
CREATE TABLE IF NOT EXISTS execution_jobs (
    job_id           TEXT PRIMARY KEY,
    approval_id      TEXT,
    work_order_id    TEXT,
    action           TEXT,
    idempotency_key  TEXT,
    status           TEXT,
    attempts         INTEGER,
    max_attempts     INTEGER,
    created_at       DOUBLE PRECISION,
    updated_at       DOUBLE PRECISION,
    payload          JSONB NOT NULL
);
"""


def _sql_literal(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        # JSONB values: JSON-encode then cast
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    # Codex S1: plain strings must NOT be JSON-encoded (no double quotes);
    # only escape single quotes per SQL standard
    return "'" + str(value).replace("'", "''") + "'"


def _ordered_ledger_rows(rows: list) -> list:
    """R15: topological order — an original always precedes its reversals.

    The ledger FK (reversal_of -> record_id) is IMMEDIATE, so a reversal
    appearing before its original in the JSON file would fail the load.
    Rows without reversals keep their file order (stable); orphan
    reversals (missing target) stay in file order for the auditor to
    report separately.
    """
    pending = [row for row in rows if isinstance(row, dict)]
    emitted_ids = set()
    ordered: list = []
    changed = True
    while pending and changed:
        changed = False
        remaining = []
        for row in pending:
            target = str(row.get("reversal_of") or "")
            if not target or target in emitted_ids:
                ordered.append(row)
                emitted_ids.add(str(row.get("record_id") or ""))
                changed = True
            else:
                remaining.append(row)
        pending = remaining
    ordered.extend(pending)  # orphans/cycles: keep file order, auditor flags them
    return ordered


def export(data_dir: Path) -> dict:
    commerce = data_dir / "commerce"
    lines = [
        "-- generated by scripts/export_commerce_to_sql.py",
        f"-- generated_at: {datetime.now(timezone.utc).isoformat()}",
        "-- ADR-0002 mapping; load into PostgreSQL is a separate approved step",
        "BEGIN;",
    ]
    counts = {}
    ledger_net = Decimal("0")
    non_cny: set = set()
    for filename, table in COMMERCE_TABLES.items():
        path = commerce / filename
        lines.append(LEDGER_DDL if table == "ledger" else COMMON_DDL.format(table=table))
        rows = []
        if path.exists():
            text = path.read_text(encoding="utf-8")
            rows = json.loads(text) if text.strip() else []
        if table == "ledger":
            rows = _ordered_ledger_rows(rows)
        counts[table] = len(rows)
        for row in rows:
            if not isinstance(row, dict):
                continue
            columns = {
                "record_id": str(row.get("record_id") or ""),
                "record_type": row.get("record_type"),
                "scope": row.get("scope"),
                "account_id": row.get("account_id"),
                "source_ref": row.get("source_ref"),
                "trace_id": row.get("trace_id"),
                "created_at": row.get("created_at"),
                "revision": row.get("revision"),
                "payload": row,
            }
            if table == "ledger":
                # the reversal FK column carries the payload's link explicitly
                columns["reversal_of"] = row.get("reversal_of")
            names = ", ".join(columns)
            values = ", ".join(_sql_literal(v) for v in columns.values())
            lines.append(f"INSERT INTO {table} ({names}) VALUES ({values});")
        if table == "offers":
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS offers_natural_key ON offers ((payload->>'provider_id'), (payload->>'source_item_id'), (payload->>'source_sku_id'), (payload->>'observed_at'), (payload->>'payload_hash'));")
        if table == "opportunities":
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS opportunities_natural_key ON opportunities ((payload->>'canonical_sku'), (payload->>'source'));")
        if table == "agent_jobs":
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS agent_jobs_idem ON agent_jobs ((payload->>'idempotency_key')) WHERE payload->>'idempotency_key' IS NOT NULL AND payload->>'idempotency_key' <> '';")
        if table == "intake_confirmations":
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS intake_confirmations_idem ON intake_confirmations ((payload->>'idempotency_key'));")
        if table == "radar_events":
            # Codex S: ADR radar idempotency -- one event per idempotency key
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS radar_events_idem ON radar_events ((payload->>'idempotency_key')) WHERE payload->>'idempotency_key' IS NOT NULL AND payload->>'idempotency_key' <> '';")
        if table == "opportunity_adoptions":
            # Codex S: ADR adoption idempotency -- one adoption per key
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS opportunity_adoptions_idem ON opportunity_adoptions ((payload->>'idempotency_key')) WHERE payload->>'idempotency_key' IS NOT NULL AND payload->>'idempotency_key' <> '';")
        if table == "procurement_orders":
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS procurement_live_sales_ref ON procurement_orders ((payload->>'sales_order_ref')) WHERE payload->>'status' <> 'cancelled';")
        if table == "inventory":
            lines.append("CREATE UNIQUE INDEX IF NOT EXISTS inventory_account_sku ON inventory ((payload->>'account_id'), (payload->>'sku'));")
        if table == "ledger":
            for row in rows:
                amount = row.get("amount") or {}
                if amount.get("state") == "known":
                    try:
                        value = Decimal(str(amount.get("amount")))
                    except (InvalidOperation, ValueError):
                        continue
                    # Codex S: the CNY reconciliation must not silently fold
                    # foreign currency into the CNY net; only an explicit
                    # conversion (none exists here) could justify that
                    if str(amount.get("currency") or "CNY") != "CNY":
                        non_cny.add(str(amount.get("currency")))
                        continue
                    ledger_net += value if row.get("direction") == "credit" else -value

    # execution authority (top-level ledger, job_id key)
    execution_path = data_dir / "execution_jobs.json"
    execution_rows = []
    if execution_path.exists():
        text = execution_path.read_text(encoding="utf-8")
        execution_rows = json.loads(text) if text.strip() else []
    counts["execution_jobs"] = len(execution_rows)
    if execution_rows:
        lines.append(EXECUTION_DDL)
        for row in execution_rows:
            if not isinstance(row, dict):
                continue
            columns = {
                "job_id": str(row.get("job_id") or ""),
                "approval_id": row.get("approval_id"),
                "work_order_id": row.get("work_order_id"),
                "action": row.get("action"),
                "idempotency_key": row.get("idempotency_key"),
                "status": row.get("status"),
                "attempts": row.get("attempts"),
                "max_attempts": row.get("max_attempts"),
                "created_at": row.get("created_at"),
                "updated_at": row.get("updated_at"),
                "payload": row,
            }
            names = ", ".join(columns)
            values = ", ".join(_sql_literal(v) for v in columns.values())
            lines.append(f"INSERT INTO execution_jobs ({names}) VALUES ({values});")
    lines.append("COMMIT;")
    footer = {
        "row_counts": counts,
        "ledger_cny_net": str(ledger_net),
        "ledger_non_cny_currencies": sorted(non_cny),
        "note": "dry-run export only; reconcile these numbers before any load",
    }
    return {"sql": "\n".join(lines) + "\n", "footer": footer}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="commerce JSON -> SQL dry-run export")
    parser.add_argument("--data-dir", required=True)
    parser.add_argument("--out", required=True, help="output .sql path (outside the data dir)")
    args = parser.parse_args(argv)
    data_dir = Path(args.data_dir).resolve()
    out = Path(args.out).resolve()
    if not data_dir.exists():
        print(json.dumps({"error": f"data dir not found: {data_dir}"}))
        return 1
    # Codex S2: the output must never point at (or inside) the authority
    # data directory; writing SQL over a live JSON ledger destroys it.
    if out == data_dir or data_dir in out.parents or out in data_dir.parents:
        print(json.dumps({"error": f"output path {out} overlaps the authority data dir {data_dir}; refusing"}))
        return 1
    # R15: a HARDLINK outside the data dir still shares the inode with an
    # authoritative JSON file — writing through it destroys the authority
    # even though the paths look disjoint. Refuse same-inode outputs.
    try:
        out_stat = out.stat() if out.exists() else None
    except OSError:
        out_stat = None
    if out_stat is not None:
        for authority_file in sorted(data_dir.rglob("*")):
            if not authority_file.is_file():
                continue
            try:
                if out.samefile(authority_file):
                    print(json.dumps({
                        "error": (
                            f"output {out} is the same file (hardlink) as authority "
                            f"{authority_file}; writing it would destroy the authority"
                        )
                    }))
                    return 1
            except OSError:
                continue
    result = export(data_dir)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(result["sql"], encoding="utf-8")
    footer = dict(result["footer"])
    footer["sql_path"] = str(out)
    print(json.dumps(footer, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
